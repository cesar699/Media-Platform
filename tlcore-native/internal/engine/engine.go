package engine

import (
	"crypto/tls"
	"fmt"
	"io"
	"net"
	"sync"
)

// InboundSpec describes one protocol listener of the native engine.
type InboundSpec struct {
	Tag      string
	Protocol string
	Port     int
	Params   map[string]string
	CertFile string // TLS protocols (self-signed cert generated by the panel layer)
	KeyFile  string
}

// Engine runs the native core's listeners.
type Engine struct {
	mu       sync.Mutex
	closers  []io.Closer
	running  bool

	// Meter, when set, receives traffic counters for every inbound.
	Meter *TrafficMeter
	// ListenPacketFn overrides UDP listener creation (tests inject an
	// in-memory transport; production leaves it nil).
	ListenPacketFn func(network, address string) (net.PacketConn, error)
	// UDPSocketFn overrides outbound UDP socket creation (same purpose).
	UDPSocketFn udpSocketFunc
}

func (e *Engine) listenPacket(network, address string) (net.PacketConn, error) {
	if e.ListenPacketFn != nil {
		return e.ListenPacketFn(network, address)
	}
	return defaultListenPacket(network, address)
}

func (e *Engine) udpSocket() (net.PacketConn, error) {
	if e.UDPSocketFn != nil {
		return e.UDPSocketFn()
	}
	return defaultUDPSocket()
}

// Running reports whether the engine has active listeners.
func (e *Engine) Running() bool {
	e.mu.Lock()
	defer e.mu.Unlock()
	return e.running
}

// Start binds all specs and serves them. If any listener fails, the
// ones already started are closed and the error is returned.
func (e *Engine) Start(specs []InboundSpec) error {
	e.mu.Lock()
	defer e.mu.Unlock()
	var closers []io.Closer
	for _, spec := range specs {
		ln, err := e.listenInbound(spec)
		if err != nil {
			for _, c := range closers {
				c.Close()
			}
			return fmt.Errorf("inbound %s: %w", spec.Tag, err)
		}
		closers = append(closers, ln)
	}
	e.closers = closers
	e.running = true
	return nil
}

// Stop closes all listeners.
func (e *Engine) Stop() {
	e.mu.Lock()
	defer e.mu.Unlock()
	for _, c := range e.closers {
		c.Close()
	}
	e.closers = nil
	e.running = false
}

func (e *Engine) listenInbound(spec InboundSpec) (io.Closer, error) {
	if spec.Protocol == "tuic" || spec.Protocol == "hysteria2" {
		return e.listenQUIC(spec)
	}
	handler, err := e.handlerFor(spec)
	if err != nil {
		return nil, err
	}
	if spec.needsTLS() {
		cert, err := tls.LoadX509KeyPair(spec.CertFile, spec.KeyFile)
		if err != nil {
			return nil, fmt.Errorf("load cert: %w", err)
		}
		ln, err := tls.Listen("tcp", fmt.Sprintf(":%d", spec.Port), &tls.Config{
			Certificates: []tls.Certificate{cert},
			MinVersion:   tls.VersionTLS12,
			NextProtos:   spec.alpn(),
		})
		if err != nil {
			return nil, err
		}
		go e.acceptLoop(ln, handler, spec.Tag)
		return ln, nil
	}
	ln, err := net.Listen("tcp", fmt.Sprintf(":%d", spec.Port))
	if err != nil {
		return nil, err
	}
	go e.acceptLoop(ln, handler, spec.Tag)
	if spec.Protocol != "shadowsocks" {
		return ln, nil
	}
	// Shadowsocks also serves UDP on the same port.
	psk, err := DecodePSK(spec.Params["password"])
	if err != nil {
		ln.Close()
		return nil, err
	}
	pc, err := e.listenPacket("udp", fmt.Sprintf(":%d", spec.Port))
	if err != nil {
		ln.Close()
		return nil, fmt.Errorf("udp listen: %w", err)
	}
	srv := &SS2022Server{PSK: psk, Meter: e.Meter, Tag: spec.Tag, UDPSocketFn: e.udpSocket}
	done := make(chan struct{})
	go func() {
		srv.ServeUDP(pc)
		close(done)
	}()
	return &multiCloser{closers: []io.Closer{ln, pc}, done: done}, nil
}

// multiCloser closes several resources as one engine listener.
type multiCloser struct {
	closers []io.Closer
	done    chan struct{}
}

func (m *multiCloser) Close() error {
	var first error
	for _, c := range m.closers {
		if err := c.Close(); err != nil && first == nil {
			first = err
		}
	}
	return first
}

func (s InboundSpec) needsTLS() bool {
	switch s.Protocol {
	case "trojan", "anytls":
		return true
	case "vless":
		return s.Params["tls"] == "true"
	}
	return false
}

func (s InboundSpec) alpn() []string {
	if s.Protocol == "anytls" || s.Protocol == "trojan" {
		return []string{"h2", "http/1.1"}
	}
	return nil
}

// HandlerCheck validates a spec's protocol and parameters by constructing
// its handler, without binding any port. Used by the panel before apply.
// listenQUIC starts a QUIC-based inbound (TUIC / Hysteria2) on a UDP
// PacketConn bound by the engine.
func (e *Engine) listenQUIC(spec InboundSpec) (io.Closer, error) {
	cert, err := tls.LoadX509KeyPair(spec.CertFile, spec.KeyFile)
	if err != nil {
		return nil, fmt.Errorf("load cert: %w", err)
	}
	pc, err := e.listenPacket("udp", fmt.Sprintf(":%d", spec.Port))
	if err != nil {
		return nil, fmt.Errorf("udp listen: %w", err)
	}
	tlsConf := &tls.Config{
		Certificates: []tls.Certificate{cert},
		MinVersion:   tls.VersionTLS12,
		NextProtos:   []string{"h3"},
	}
	var closer io.Closer
	switch spec.Protocol {
	case "tuic":
		uuid, err := ParseUUID(spec.Params["uuid"])
		if err != nil {
			pc.Close()
			return nil, err
		}
		srv := &TUICServer{UUID: uuid, Password: spec.Params["password"], Meter: e.Meter, Tag: spec.Tag, UDPSocketFn: e.udpSocket}
		closer, err = srv.Serve(pc, tlsConf)
		if err != nil {
			pc.Close()
			return nil, err
		}
	case "hysteria2":
		srv := &HY2Server{Password: spec.Params["password"], Meter: e.Meter, Tag: spec.Tag, UDPSocketFn: e.udpSocket}
		closer, err = srv.Serve(pc, tlsConf)
		if err != nil {
			pc.Close()
			return nil, err
		}
	}
	return closer, nil
}

func HandlerCheck(spec InboundSpec) (bool, error) {
	switch spec.Protocol {
	case "tuic":
		if _, err := ParseUUID(spec.Params["uuid"]); err != nil {
			return false, err
		}
		if spec.Params["password"] == "" {
			return false, fmt.Errorf("tuic: password required")
		}
		return true, nil
	case "hysteria2":
		if spec.Params["password"] == "" {
			return false, fmt.Errorf("hysteria2: password required")
		}
		return true, nil
	}
	_, err := (&Engine{}).handlerFor(spec)
	return err == nil, err
}

type connHandler func(net.Conn)

func (e *Engine) acceptLoop(ln net.Listener, h connHandler, tag string) {
	for {
		c, err := ln.Accept()
		if err != nil {
			return
		}
		go func(c net.Conn) {
			e.Meter.Open(tag)
			defer e.Meter.Close(tag)
			h(e.Meter.wrapConn(tag, c))
		}(c)
	}
}

func (e *Engine) handlerFor(spec InboundSpec) (connHandler, error) {
	switch spec.Protocol {
	case "shadowsocks":
		psk, err := DecodePSK(spec.Params["password"])
		if err != nil {
			return nil, err
		}
		srv := &SS2022Server{PSK: psk}
		return srv.Handle, nil
	case "trojan":
		srv := &TrojanServer{Password: spec.Params["password"], UDPSocketFn: e.udpSocket}
		return srv.Handle, nil
	case "anytls":
		srv := &AnyTLSServer{Password: spec.Params["password"]}
		return srv.Handle, nil
	case "vless":
		srv := &VLESSServer{UUID: spec.Params["uuid"], UDPSocketFn: e.udpSocket}
		return srv.Handle, nil
	case "vmess":
		srv := &VMessServer{UUID: spec.Params["uuid"], UDPSocketFn: e.udpSocket}
		return srv.Handle, nil
	}
	return nil, fmt.Errorf("protocol %q not yet implemented in the native engine", spec.Protocol)
}
